/*
# Order tracking: locked status writes, fulfillment details, buyer notifications, realtime

1. Changes
- Order status history is append-only for ordinary users: only SELECT is granted; all changes go through transition_order_status.
- Orders and deliveries can no longer be edited directly by signed-in users; the status function and set_fulfillment_details are the only write paths.
- New function set_fulfillment_details lets the seller of an order record courier, tracking number, and fulfillment notes.
- Each status history row creates an in-app notification for the buyer that links to the tracking page.
- orders, order_status_history, deliveries, and notifications are published to Realtime so the app receives live changes (RLS still applies).

2. Security
- Revokes UPDATE on orders, INSERT/UPDATE/DELETE/TRUNCATE on order_status_history and deliveries from anon and authenticated.
- set_fulfillment_details is SECURITY DEFINER, callable only by authenticated, and checks that the caller is the seller of the order or an admin.

3. Notes
- Notifications are generated by a trigger on status history, so one transition creates exactly one notification.
- Email preferences are not used here because this app does not send order emails yet.
*/

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime'
  ) THEN
    CREATE PUBLICATION supabase_realtime;
  END IF;
END $$;

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['orders', 'order_status_history', 'deliveries', 'notifications'] LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_publication_tables
      WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = t
    ) THEN
      EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
    END IF;
  END LOOP;
END $$;

REVOKE UPDATE ON orders FROM anon, authenticated;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON order_status_history FROM anon, authenticated;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON deliveries FROM anon, authenticated;

CREATE INDEX IF NOT EXISTS idx_order_status_history_order_created
  ON order_status_history (order_id, created_at);

CREATE OR REPLACE FUNCTION public.set_fulfillment_details(
  p_order_id uuid,
  p_courier text,
  p_tracking_number text,
  p_notes text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_status text;
  v_is_seller boolean;
  v_courier text := NULLIF(btrim(COALESCE(p_courier, '')), '');
  v_tracking text := NULLIF(btrim(COALESCE(p_tracking_number, '')), '');
  v_notes text := NULLIF(btrim(COALESCE(p_notes, '')), '');
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'You must be signed in.';
  END IF;

  IF char_length(COALESCE(v_courier, '')) > 100
     OR char_length(COALESCE(v_tracking, '')) > 100
     OR char_length(COALESCE(v_notes, '')) > 500 THEN
    RAISE EXCEPTION 'Courier, tracking number, or notes are too long.';
  END IF;

  SELECT status INTO v_status FROM orders WHERE id = p_order_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Order not found.';
  END IF;

  v_is_seller := EXISTS (
    SELECT 1 FROM order_items oi
    JOIN seller_profiles sp ON sp.id = oi.seller_id AND sp.user_id = v_actor
    WHERE oi.order_id = p_order_id
  );

  IF NOT (v_is_seller OR public.is_admin()) THEN
    RAISE EXCEPTION 'You are not authorized to update this order.';
  END IF;

  IF v_status NOT IN ('confirmed', 'processing', 'ready_for_pickup', 'shipped') THEN
    RAISE EXCEPTION 'Fulfillment details can only be added to an order that is confirmed or in progress.';
  END IF;

  UPDATE deliveries
  SET courier = v_courier,
      tracking_number = v_tracking,
      notes = v_notes,
      updated_at = now()
  WHERE order_id = p_order_id;

  IF NOT FOUND THEN
    INSERT INTO deliveries (order_id, courier, tracking_number, notes)
    VALUES (p_order_id, v_courier, v_tracking, v_notes);
  END IF;
END;
$function$;

REVOKE EXECUTE ON FUNCTION public.set_fulfillment_details(uuid, text, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.set_fulfillment_details(uuid, text, text, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.notify_buyer_order_status()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_buyer uuid;
  v_order_number text;
  v_title text;
  v_body text;
BEGIN
  SELECT buyer_id, order_number INTO v_buyer, v_order_number FROM orders WHERE id = NEW.order_id;

  v_title := CASE NEW.new_status
    WHEN 'confirmed' THEN 'Order confirmed'
    WHEN 'processing' THEN 'Your order is being prepared'
    WHEN 'ready_for_pickup' THEN 'Ready for pickup'
    WHEN 'shipped' THEN 'Your order has shipped'
    WHEN 'delivered' THEN 'Your order was delivered'
    WHEN 'cancelled' THEN 'Order cancelled'
    WHEN 'refunded' THEN 'Order refunded'
    WHEN 'disputed' THEN 'Order disputed'
    ELSE NULL
  END;

  IF v_title IS NULL THEN
    RETURN NEW;
  END IF;

  v_body := 'Order ' || COALESCE(v_order_number, '') || ' is now ' || replace(NEW.new_status, '_', ' ') || '.';

  INSERT INTO notifications (user_id, type, title, body, link, data)
  VALUES (
    v_buyer,
    'order',
    v_title,
    v_body,
    '/orders/' || NEW.order_id::text || '/track',
    jsonb_build_object('order_id', NEW.order_id, 'status', NEW.new_status, 'history_id', NEW.id)
  );

  RETURN NEW;
END;
$function$;

REVOKE EXECUTE ON FUNCTION public.notify_buyer_order_status() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS order_status_history_notify_buyer ON order_status_history;
CREATE TRIGGER order_status_history_notify_buyer
AFTER INSERT ON order_status_history
FOR EACH ROW EXECUTE FUNCTION public.notify_buyer_order_status();
